import importlib
from types import ModuleType

from xcp_storage.typing import Final, Optional

# ==============================================================================

_UNKNOWN_ATTRIBUTE: Final = "unknown"

# `xcp_storage.build_info` is generated by CMake (see `build_info.py.in`).
# It does not exist when the python project is installed without CMake step.
_build_info: Optional[ModuleType]
try:
    _build_info = importlib.import_module("xcp_storage.build_info")
except ImportError:
    _build_info = None

class XcpStorageVersion:
    RELEASE: Final = getattr(_build_info, "RELEASE", _UNKNOWN_ATTRIBUTE)
    GIT_COMMIT: Final = getattr(_build_info, "GIT_COMMIT", _UNKNOWN_ATTRIBUTE)
    BUILD_DATE: Final = getattr(_build_info, "BUILD_DATE", _UNKNOWN_ATTRIBUTE)

    @classmethod
    def get_description(cls) -> str:
        return f"{cls.RELEASE} (commit {cls.GIT_COMMIT}, built {cls.BUILD_DATE})"
