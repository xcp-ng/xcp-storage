import importlib
from pathlib import Path

from xcp_storage.typing import Dict, Final

# ==============================================================================

PROJECT_PATH: Final = Path(__file__).parents[1]

# Directory of the daemons in the sources.
PROJECT_DAEMONS_DIR_PATH: Final = PROJECT_PATH / "daemons"

# ------------------------------------------------------------------------------

BUILD_CONFIG_CMAKE_VARIABLE_PREFIX: Final = "XCP_STORAGE_"

# ------------------------------------------------------------------------------

def get_build_config_cmake_variables() -> Dict[str, str]:
    """
    Get the CMake variables of the settings of the current build (`build_config.py`),
    to configure another build for the same target platform.
    """

    # Settings of the target platform, generated by CMake from the preset:
    # the constant `X` of the module comes from the CMake variable `XCP_STORAGE_X`
    # (see `build_config.py.in`).
    build_config = importlib.import_module("xcp_storage.config.build_config")
    return {
        f"{BUILD_CONFIG_CMAKE_VARIABLE_PREFIX}{name}": value
        for name, value in vars(build_config).items()
        if name.isupper()
    }
